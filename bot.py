def reset_test(context):
    context.user_data["question"] = 0
    context.user_data["scores"] = {
        "girl": 0,
        "muse": 0,
        "queen": 0,
        "amazon": 0,
        "witch": 0,
        "mother": 0,
    }


def main_keyboard():
    return InlineKeyboardMarkup([
        [InlineKeyboardButton("✨ Начать тест", callback_data="start_test")]
    ])


def question_keyboard(question_index):
    question = QUESTIONS[question_index]

    buttons = []

    for i, (answer_text, archetype) in enumerate(question["answers"]):
        letter = chr(65 + i)
        buttons.append([
            InlineKeyboardButton(
                f"{letter}. {answer_text}",
                callback_data=f"answer:{archetype}"
            )
        ])

    return InlineKeyboardMarkup(buttons)


async def send_question(update, context):
    index = context.user_data["question"]
    question = QUESTIONS[index]

    text = (
        f"🌸 <b>Вопрос {index + 1} из {len(QUESTIONS)}</b>\n\n"
        f"{question['text']}"
    )

    await update.effective_chat.send_message(
        text=text,
        parse_mode="HTML",
        reply_markup=question_keyboard(index),
    )


