# ============================================================
# НАЧАЛО ТЕСТА
# ============================================================

async def start_test(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    reset_test(context)

    await query.message.delete()

    await send_question(update, context)


# ============================================================
# ОБРАБОТКА ОТВЕТА
# ============================================================

async def answer_question(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    archetype = query.data.split(":")[1]

    # Начисляем балл
    context.user_data["scores"][archetype] += 1

    # Переходим к следующему вопросу
    context.user_data["question"] += 1

    await query.message.delete()

    if context.user_data["question"] >= len(QUESTIONS):
        await show_result(update, context)
    else:
        await send_question(update, context)


# ============================================================
# РЕЗУЛЬТАТ
# ============================================================

async def show_result(update: Update, context: ContextTypes.DEFAULT_TYPE):
    scores = context.user_data["scores"]

    total = sum(scores.values())

    # Сортируем архетипы по количеству баллов
    ranking = sorted(
        scores.items(),
        key=lambda item: item[1],
        reverse=True
    )

    leading_key = ranking[0][0]

    # Архетип с минимальным количеством баллов.
    # При равенстве выбирается последний в сортировке.
    sleeping_key = ranking[-1][0]

    leading_score = scores[leading_key]

    lines = [
        "✨ <b>Твой результат</b>\n",
        f"Твой ведущий архетип — <b>{ARCHETYPES[leading_key]}</b>\n",
        f"У тебя {leading_score} из {len(QUESTIONS)} баллов.\n",
        "\n<b>Твой профиль:</b>",
    ]

    for key, score in ranking:
        percentage = round(score / total * 100)
        lines.append(
            f"{ARCHETYPES[key]} — {score} балл. ({percentage}%)"
        )

    lines.append("\n")
    lines.append(RESULTS[leading_key]["text"])

    if sleeping_key != leading_key:
        lines.append(
            f"\n\n🌙 <b>Архетип, которому сейчас может быть полезно "
            f"дать больше пространства:</b>\n"
            f"{ARCHETYPES[sleeping_key]}\n\n"
            f"{RESULTS[sleeping_key]['text']}"
        )

    keyboard = InlineKeyboardMarkup([
        [InlineKeyboardButton("🔄 Пройти тест ещё раз", callback_data="restart")]
    ])

    await update.effective_chat.send_message(
        text="\n".join(lines),
        parse_mode="HTML",
        reply_markup=keyboard,
    )


# ============================================================
# ПЕРЕЗАПУСК
# ============================================================

async def restart(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    reset_test(context)

    await query.message.delete()

    await send_question(update, context)


# ============================================================
# HELP
# ============================================================

async def help_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "Чтобы пройти тест, нажми /start"
    )


# ============================================================
# ЗАПУСК
# ============================================================

def main():
    application = Application.builder().token(TOKEN).build()

    application.add_handler(CommandHandler("start", start))
    application.add_handler(CommandHandler("test", start))
    application.add_handler(CommandHandler("help", help_command))

    application.add_handler(
        CallbackQueryHandler(start_test, pattern="^start_test$")
    )

    application.add_handler(
        CallbackQueryHandler(answer_question, pattern="^answer:")
    )

    application.add_handler(
        CallbackQueryHandler(restart, pattern="^restart$")
    )

    application.run_polling()


if __name__ == "__main__":
    main()
